/** Opt-in compatibility reads. Caller must authorize branch codes before opening. */
const relations=`WITH review_candidates AS (
 SELECT l.global_vendor_code,l.review_id,l.store_name,l.review_date,l.rating,l.payload,0 AS priority
 FROM public.talabat_text_reviews l WHERE l.global_vendor_code=ANY($1::text[])
 UNION ALL
 SELECT n.vendor,n.review_id,coalesce(b.store_name,l.store_name),n.review_date,n.rating,
 jsonb_build_object('id',n.review_id,'globalVendorCode',n.vendor,'orderId',coalesce(n.order_id,nullif(l.payload->>'orderId','')),
 'date',n.review_date,'rating',n.rating,'text',n.review_text,'isAutoGenerated',n.generated,'reply',l.payload->'reply','customerDetails',l.payload->'customerDetails'),1
 FROM public.review_v2_reviews n LEFT JOIN public.talabat_text_reviews l ON l.global_vendor_code=n.vendor AND l.review_id=n.review_id
 LEFT JOIN public.talabat_review_branches b ON b.global_vendor_code=n.vendor WHERE n.vendor=ANY($1::text[])
), ranked_reviews AS (SELECT *,row_number() OVER(PARTITION BY global_vendor_code,review_id ORDER BY priority DESC) AS position FROM review_candidates),
 talabat_text_reviews AS (SELECT * FROM ranked_reviews WHERE position=1),
 order_candidates AS (
 SELECT global_vendor_code,order_id,payload,'LEGACY_UNVERIFIED'::text AS link_state,0 AS priority FROM public.talabat_review_orders WHERE global_vendor_code=ANY($1::text[])
 UNION ALL SELECT vendor,order_id,details,'VERIFIED',1 FROM public.review_v2_orders WHERE vendor=ANY($1::text[]) AND details IS NOT NULL AND verified_at IS NOT NULL
), ranked_orders AS (SELECT *,row_number() OVER(PARTITION BY global_vendor_code,order_id ORDER BY priority DESC) AS position FROM order_candidates),
 talabat_review_orders AS (SELECT * FROM ranked_orders WHERE position=1),
 coverage_intervals AS (
 SELECT global_vendor_code,period_from,period_to,completed_at FROM public.talabat_review_coverage WHERE global_vendor_code=ANY($1::text[])
 UNION ALL SELECT vendor,period_from,period_to,completed_at FROM public.review_v2_coverage WHERE vendor=ANY($1::text[])
), previous_intervals AS (
 SELECT *,max(period_to) OVER(PARTITION BY global_vendor_code ORDER BY period_from,period_to ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS previous_to FROM coverage_intervals
), interval_groups AS (
 SELECT *,sum(CASE WHEN previous_to IS NULL OR period_from>previous_to+interval '1 millisecond' THEN 1 ELSE 0 END) OVER(PARTITION BY global_vendor_code ORDER BY period_from,period_to) AS island FROM previous_intervals
), talabat_review_coverage AS (
 SELECT global_vendor_code,min(period_from) AS period_from,max(period_to) AS period_to,max(completed_at) AS completed_at FROM interval_groups GROUP BY global_vendor_code,island
) `;

export async function openCombinedReviewsRead(pool:any,codes:string[]){
 if(typeof pool.connect!=='function')throw Error('REVIEWS_COMBINED_DATABASE_REQUIRED');
 const client=await pool.connect();let committed=false,discard=false;
 try{
  await client.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');await client.query("SET LOCAL statement_timeout='8000ms'");
  const conflict=await client.query(`SELECT 1 FROM public.review_v2_reviews n JOIN public.talabat_text_reviews l ON l.global_vendor_code=n.vendor AND l.review_id=n.review_id
   WHERE n.vendor=ANY($1::text[]) AND n.order_id IS NOT NULL AND nullif(l.payload->>'orderId','') IS NOT NULL AND n.order_id<>l.payload->>'orderId' LIMIT 1`,[codes]);
  if(conflict.rows.length)throw Error('REVIEWS_ORDER_LINK_CONFLICT');
 }catch{try{await client.query('ROLLBACK');}catch{discard=true;}client.release(discard);throw Error('REVIEWS_COMBINED_READ_FAILED');}
 return {
  db:{query:async(sql:string,values:any[])=>{
   if(!Array.isArray(values?.[0])||values[0].some((code:string)=>!codes.includes(code)))throw Error('REVIEWS_SCOPE_INVALID');
   return client.query(relations+sql,values);
  }},
  commit:async()=>{await client.query('COMMIT');committed=true;},
  close:async()=>{if(!committed)try{await client.query('ROLLBACK');}catch{discard=true;}client.release(discard);}
 };
}
